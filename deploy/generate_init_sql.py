#!/usr/bin/env python3
"""Regenerate deploy/init.sql — the single-file zero-to-running bootstrap.

    python deploy/generate_init_sql.py

init.sql = consolidated schema (net effect of deploy/migrations/001-008)
+ schema_migrations seed rows (so init_db.py only applies NEWER migrations)
+ default site / admin user / owner membership (psql -v variables)
+ the shipped config/*.json embedded as site_configs rows (validated through
  the Pydantic schemas at generation time).

Run this after changing config/*.json or adding a migration whose state
should be part of a fresh install, then commit the regenerated init.sql.
"""

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
CONFIG_DIR = PROJECT_ROOT / "config"
MIGRATIONS_DIR = Path(__file__).resolve().parent / "migrations"
OUT = Path(__file__).resolve().parent / "init.sql"

sys.path.insert(0, str(PROJECT_ROOT / "backend"))

from config.rules_schema import RulesConfig            # noqa: E402
from config.schemas import UnifiedOntologyConfig       # noqa: E402
from config.strategies_schema import StrategiesConfig  # noqa: E402

CONFIG_SCHEMAS = {
    "ontology": UnifiedOntologyConfig,
    "rules": RulesConfig,
    "strategies": StrategiesConfig,
}

HEADER = """\
-- ============================================================================
-- AI-CDP — zero-to-running bootstrap (PostgreSQL 12+)
--
-- GENERATED by deploy/generate_init_sql.py — do not edit by hand.
--
-- Takes a FRESH database to a state where the service runs:
--   schema (net effect of migrations 001-008) + default site + admin user
--   + ontology/rules/strategies configs. Idempotent — safe to re-run.
--
-- Usage:
--   psql "$DATABASE_URL" -f deploy/init.sql \\
--        -v admin_email="you@company.com" -v admin_name="You" \\
--        -v site_name="My Company"
--   (every -v is optional; defaults below)
--
-- Afterwards the service needs only DATABASE_URL (+ JWT_SECRET,
-- GOOGLE_CLIENT_ID, APP_ENCRYPTION_KEY in production) — no DEV_MODE.
-- Future schema upgrades: python deploy/init_db.py --database-url "..."
-- (this file pre-seeds schema_migrations so only NEW migrations run).
-- ============================================================================

\\if :{?admin_email} \\else \\set admin_email 'admin@example.com' \\endif
\\if :{?admin_name}  \\else \\set admin_name  'Admin'             \\endif
\\if :{?site_name}   \\else \\set site_name   'Default Site'      \\endif

BEGIN;

-- ── Tenancy ─────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS sites (
    id SERIAL PRIMARY KEY,
    name VARCHAR(256) NOT NULL,
    slug VARCHAR(64) UNIQUE NOT NULL,
    settings JSONB DEFAULT '{}',
    created_at TIMESTAMPTZ DEFAULT NOW()
);
COMMENT ON TABLE sites IS 'Tenant registry. Each site is an isolated workspace with its own config and data sources.';
COMMENT ON COLUMN sites.settings IS 'Site-level settings JSONB: {"max_iterations": 3, "sql_policy": {...}, "guardrail_level": "strict"}';

CREATE TABLE IF NOT EXISTS data_sources (
    id SERIAL PRIMARY KEY,
    site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    name VARCHAR(256) NOT NULL DEFAULT 'default',
    db_type VARCHAR(32) NOT NULL,
    connection_config JSONB NOT NULL,
    secrets_encrypted BYTEA,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
COMMENT ON TABLE data_sources IS 'Per-site analytics-DB connections (greenplum, postgresql, ...).';
COMMENT ON COLUMN data_sources.connection_config IS 'NON-SECRET connection details: {host, port, dbname, user, readonly_user}.';
COMMENT ON COLUMN data_sources.secrets_encrypted IS 'Fernet-encrypted JSON: {password, readonly_password}. Encrypted with APP_ENCRYPTION_KEY.';
CREATE INDEX IF NOT EXISTS idx_data_sources_site_id ON data_sources(site_id);

CREATE TABLE IF NOT EXISTS users (
    id SERIAL PRIMARY KEY,
    google_id VARCHAR(128) UNIQUE NOT NULL,
    email VARCHAR(256) NOT NULL,
    name VARCHAR(256),
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
COMMENT ON TABLE users IS 'Users authenticated via Google OAuth. google_id is the sub claim from the ID token.';
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_unique ON users(email);

CREATE TABLE IF NOT EXISTS site_members (
    site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(32) NOT NULL DEFAULT 'member',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (site_id, user_id)
);
COMMENT ON TABLE site_members IS 'Maps users to sites with roles: owner, admin, member.';

-- ── Config storage & governance ─────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS site_configs (
    id SERIAL PRIMARY KEY,
    site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    config_type VARCHAR(32) NOT NULL,
    config_data JSONB NOT NULL,
    version VARCHAR(32) NOT NULL,
    updated_by INTEGER REFERENCES users(id),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(site_id, config_type)
);
COMMENT ON TABLE site_configs IS 'Per-site configuration storage (ontology, rules, strategies, sql_tools, ...).';
CREATE INDEX IF NOT EXISTS idx_site_configs_site ON site_configs (site_id);

CREATE TABLE IF NOT EXISTS config_audit_log (
    id SERIAL PRIMARY KEY,
    site_id INTEGER NOT NULL,
    config_type VARCHAR(32) NOT NULL,
    action VARCHAR(16) NOT NULL CHECK (action IN ('create', 'update', 'delete')),
    changed_by INTEGER NOT NULL REFERENCES users(id),
    previous_data JSONB,
    new_data JSONB,
    diff_json JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
COMMENT ON TABLE config_audit_log IS 'Audit trail for all config changes with who/when/what (+ field-level diff).';
CREATE INDEX IF NOT EXISTS idx_audit_site_time ON config_audit_log (site_id, created_at DESC);

CREATE TABLE IF NOT EXISTS action_executions (
    id SERIAL PRIMARY KEY,
    site_id INTEGER NOT NULL REFERENCES sites(id),
    action_type TEXT NOT NULL,
    target_node_key TEXT,
    request_json JSONB,
    response_json JSONB,
    execution_status TEXT NOT NULL DEFAULT 'succeeded',
    error_message TEXT,
    executed_by INTEGER REFERENCES users(id),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    correlation_id TEXT
);
CREATE INDEX IF NOT EXISTS idx_action_executions_site ON action_executions(site_id);
CREATE INDEX IF NOT EXISTS idx_action_executions_type ON action_executions(action_type);
CREATE INDEX IF NOT EXISTS idx_action_executions_target ON action_executions(target_node_key);

-- ── Long-term agent memory ──────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS memories (
    id          SERIAL PRIMARY KEY,
    app_name    TEXT NOT NULL,
    user_id     TEXT NOT NULL,
    session_id  TEXT NOT NULL,
    site_id     INTEGER REFERENCES sites(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,
    author      TEXT NOT NULL DEFAULT 'model',
    "timestamp" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    content     JSONB NOT NULL,
    text        TEXT NOT NULL,
    tsv         TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', text)) STORED
);
COMMENT ON TABLE memories IS 'Long-term agent memory: distilled session facts, site-scoped, full-text searchable.';
CREATE INDEX IF NOT EXISTS idx_memories_tsv ON memories USING GIN (tsv);
CREATE INDEX IF NOT EXISTS idx_memories_user ON memories (app_name, user_id);
CREATE INDEX IF NOT EXISTS idx_memories_session ON memories (app_name, user_id, session_id);

-- ── Per-site external service credentials ───────────────────────────────────
-- KEY CUSTODY: encrypted columns are Fernet tokens under APP_ENCRYPTION_KEY.
-- Losing that key makes stored secrets unrecoverable (metadata survives).

CREATE TABLE IF NOT EXISTS external_credentials (
    id SERIAL PRIMARY KEY,
    site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    service VARCHAR(64) NOT NULL,
    credentials_encrypted BYTEA NOT NULL,
    metadata JSONB DEFAULT '{}',
    is_active BOOLEAN DEFAULT true,
    created_by INTEGER REFERENCES users(id),
    updated_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (site_id, service)
);
COMMENT ON TABLE external_credentials IS 'Per-site external service credentials (gemini, vertex_ai, ...), Fernet-encrypted with APP_ENCRYPTION_KEY.';
COMMENT ON COLUMN external_credentials.metadata IS 'NON-SECRET display fields only: {project_id, location, key_hint}.';
CREATE INDEX IF NOT EXISTS idx_external_credentials_site ON external_credentials (site_id);

-- ── Migration ledger (pre-seeded so init_db.py only applies NEW migrations) ─

CREATE TABLE IF NOT EXISTS schema_migrations (
    filename VARCHAR(256) PRIMARY KEY,
    applied_at TIMESTAMPTZ DEFAULT NOW()
);

__MIGRATION_SEEDS__

-- ── Seed: site + admin (owner) ──────────────────────────────────────────────

INSERT INTO sites (name, slug, settings)
VALUES (:'site_name', 'default', '{"max_iterations": 3}')
ON CONFLICT (slug) DO NOTHING;

INSERT INTO users (google_id, email, name)
VALUES ('init:' || :'admin_email', :'admin_email', :'admin_name')
ON CONFLICT (email) DO NOTHING;

INSERT INTO site_members (site_id, user_id, role)
SELECT s.id, u.id, 'owner'
FROM sites s, users u
WHERE s.slug = 'default' AND u.email = :'admin_email'
ON CONFLICT (site_id, user_id) DO NOTHING;

-- ── Seed: shipped configs (ontology / rules / strategies) ───────────────────
-- Embedded from config/*.json at generation time, schema-validated.
"""

FOOTER = """
COMMIT;

\\echo
\\echo 'AI-CDP bootstrap complete.'
\\echo 'Site:' :site_name '| admin (owner):' :admin_email
\\echo 'Next: set DATABASE_URL in the service environment and start it.'
"""


def main() -> None:
    migration_seeds = "\n".join(
        f"INSERT INTO schema_migrations (filename) VALUES ('{p.name}') "
        "ON CONFLICT (filename) DO NOTHING;"
        for p in sorted(MIGRATIONS_DIR.glob("*.sql"))
    )

    config_inserts = []
    for config_type, schema in CONFIG_SCHEMAS.items():
        path = CONFIG_DIR / f"{config_type}.json"
        config = schema(**json.loads(path.read_text(encoding="utf-8")))
        payload = json.dumps(config.model_dump(), ensure_ascii=False)
        if "$json$" in payload:
            raise ValueError(f"{path.name} contains the dollar-quote tag")
        config_inserts.append(
            f"INSERT INTO site_configs (site_id, config_type, config_data, version)\n"
            f"SELECT s.id, '{config_type}', $json${payload}$json$::jsonb, "
            f"'{config.version}'\n"
            f"FROM sites s WHERE s.slug = 'default'\n"
            f"ON CONFLICT (site_id, config_type) DO NOTHING;"
        )

    sql = (
        HEADER.replace("__MIGRATION_SEEDS__", migration_seeds)
        + "\n"
        + "\n\n".join(config_inserts)
        + "\n"
        + FOOTER
    )
    OUT.write_text(sql, encoding="utf-8")
    print(f"Wrote {OUT} ({len(sql):,} bytes)")


if __name__ == "__main__":
    main()
